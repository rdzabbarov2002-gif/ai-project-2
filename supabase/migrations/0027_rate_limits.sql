-- Audit: rate limits that count requests, not finished generations.
--
-- The per-minute limit on /api/generate counted the caller's saved
-- generations — rows written only after the AI call, many seconds later,
-- so requests sent at once all passed it. And a guest is whatever session
-- token the browser sends: each new token was a new guest, with its own
-- free generations and its own per-minute limit.
--
-- Now every request a limit lets through is recorded here, under what it
-- is limited by (lib/limits/rateLimit.ts): the user or guest session for
-- the per-minute limit, and for requests without an account the IP
-- address — as a keyed hash that changes every day, never the address
-- itself. Rows older than a day are deleted nightly
-- (app/api/cron/purge-expired), with expired guest sessions.
--
-- Server only, like feedback (migration 0022).

create table public.rate_limit_events (
  id bigint generated by default as identity primary key,
  subject text not null,
  created_at timestamptz not null default now()
);

create index rate_limit_events_subject_created_at_idx
  on public.rate_limit_events (subject, created_at desc);

alter table public.rate_limit_events enable row level security;
revoke all on table public.rate_limit_events from anon, authenticated;

-- Lets one more request through for `p_subject` — and records it — when
-- fewer than `p_max` were let through in the last `p_window_seconds`;
-- refused requests aren't recorded. Calls for the same subject take turns
-- (a lock held to the end of the call), so requests sent at once can't
-- all find room for one more.
create function public.take_rate_limit(p_subject text, p_max integer, p_window_seconds integer)
returns boolean
language plpgsql
set search_path = ''
as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(p_subject, 0));

  if (
    select count(*) from public.rate_limit_events
    where subject = p_subject
      and created_at > now() - make_interval(secs => p_window_seconds)
  ) >= p_max then
    return false;
  end if;

  insert into public.rate_limit_events (subject) values (p_subject);
  return true;
end;
$$;

-- Server only (the admin client), like increment_usage_counter (0011).
revoke all on function public.take_rate_limit(text, integer, integer) from public, anon, authenticated;
grant execute on function public.take_rate_limit(text, integer, integer) to service_role;
